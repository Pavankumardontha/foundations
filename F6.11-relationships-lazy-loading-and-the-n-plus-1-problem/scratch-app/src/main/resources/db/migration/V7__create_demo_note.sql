-- F6.11 Lesson 17: a throwaway table with a DATABASE-GENERATED id.
-- Its only job is to show the before/after-save problem (subtask S13): the id is
-- null before save and assigned by the database after save, so any equals/hashCode
-- built on the id changes across save.
CREATE TABLE demo_note (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body text NOT NULL
);
