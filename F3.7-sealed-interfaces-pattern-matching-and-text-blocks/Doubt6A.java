public class Doubt6A {

    public static void main(String[] args) {
        // A normal string lives on ONE line of code.
        // To get a line break INSIDE it, you must type \n.
        String s = "hello\nworld";
        System.out.println(s);

        System.out.println("-----");

        // To get a quote INSIDE it, you must type \"
        String j = "{ \"name\": \"Asha\" }";
        System.out.println(j);
    }
}
